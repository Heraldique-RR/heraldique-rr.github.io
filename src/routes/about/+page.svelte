<h1>À propos</h1>

<p>
	Ce site est un projet dédié à la découverte et à la valorisation de l'<strong>héraldique</strong>,
	l'art et la science des armoiries.
</p>

<h2>Notre mission</h2>

<p>Rendre l'héraldique accessible à tous, en proposant :</p>

<ul>
	<li>Des <strong>explications claires</strong> sur les règles du blason</li>
	<li>Des <strong>exemples historiques</strong> d'armoiries célèbres</li>
	<li>Des <strong>ressources</strong> pour les passionnés et les chercheurs</li>
	<li>Un <strong>lexique</strong> des termes héraldiques</li>
</ul>

<h2>L'héraldique en bref</h2>

<p>
	L'héraldique est apparue au XII<sup>e</sup> siècle en Europe, principalement pour identifier les
	chevaliers sur les champs de bataille. Elle s'est ensuite développée pour devenir un véritable
	langage symbolique utilisé par les familles nobles, les institutions, les villes et les États.
</p>

<p>
	Aujourd'hui, l'héraldique reste vivante : elle est utilisée dans les armoiries nationales, les
	logos d'institutions, et continue d'inspirer artistes et designers.
</p>

